import {test} from 'node:test';
import assert from 'node:assert/strict';
import {localDatabase} from './sqlite-adapter.mjs';
import {handle} from '../dist-classroom/worker.mjs';
const origin='https://mahrush666.github.io';
function setup(){const DB=localDatabase();const env={DB,ALLOWED_ORIGINS:origin,TEACHER_PASSWORD:'test-teacher-password'};let seq=0;
 return {DB,async api(path,body,token){const r=await handle(new Request('https://classroom.test'+path,{method:body===undefined?'GET':'POST',headers:{Origin:origin,...(token?{Authorization:'Bearer '+token}:{}),'Content-Type':'application/json','CF-Connecting-IP':'test-'+seq++},body:body===undefined?undefined:JSON.stringify(body)}),env);return {status:r.status,body:await r.json()}}};}
test('parent registration, child approval, class-specific assignments, protected progress and teacher reports',async()=>{
 const {api,DB}=setup();
 const teacher=(await api('/teacher-login',{password:'test-teacher-password'})).body.token;
 const a=(await api('/groups',{name:'Tuesday Starter'},teacher)).body;
 const b=(await api('/groups',{name:'Saturday Readers'},teacher)).body;
 const parent=(await api('/register',{username:'panda_family',password:'parent-password',consent:true})).body.token;
 const other=(await api('/register',{username:'other_family',password:'parent-password',consent:true})).body.token;
 assert.equal((await api('/groups',{name:'Unauthorized'},parent)).status,403);
 assert.equal((await api('/teacher-login',{password:'wrong'})).status,401);
 const kid=(await api('/children',{name:'Amy',invite:a.invite},parent)).body.id;
 assert.equal((await api('/homework?child='+kid,undefined,parent)).body.pending,true);
 assert.equal((await api('/homework?child='+kid,undefined,other)).status,404);
 await api('/approve',{childId:kid,approved:true},teacher);
 const payload={groupId:a.id,unitId:'pu-starter-u7-lesson1',activities:['picture-listen'],wordIds:['pu-starter-u7-climb','pu-starter-u7-swim','pu-starter-u7-walk','pu-starter-u7-jump'],title:'Four actions',dueDate:'2026-10-20'};
 const saved=await api('/assignments',payload,teacher);assert.equal(saved.status,200);
 const assignmentId=saved.body.id;
 assert.equal((await api('/assignments',{...payload,activities:['picture-speak']},teacher)).status,400);
 assert.equal((await api('/assignments',{...payload,wordIds:['pu-starter-u7-climb']},teacher)).status,400);
 const otherAssignment=(await api('/assignments',{...payload,groupId:b.id,activities:['cards']},teacher)).body.id;
 let homework=(await api('/homework?child='+kid,undefined,parent)).body;
 assert.equal(homework.assignments.length,1);assert.deepEqual(JSON.parse(homework.assignments[0].activities),['picture-listen']);
 const event={childId:kid,assignmentId,activity:'picture-listen',wordId:'pu-starter-u7-climb',correct:true,eventId:crypto.randomUUID()};
 assert.equal((await api('/progress',{...event,assignmentId:otherAssignment},parent)).status,400);
 assert.equal((await api('/progress',{...event,activity:'cards'},parent)).status,400);
 assert.equal((await api('/progress',{...event,wordId:'pu-starter-u7-run'},parent)).status,400);
 assert.equal((await api('/progress',event,other)).status,404);
 assert.equal((await api('/progress',event,parent)).status,200);
 const initial=(await api('/homework?child='+kid,undefined,parent)).body.progress['pu-starter-u7-climb'];
 assert.equal(initial.step,1);
 assert.equal((await api('/progress',event,parent)).body.duplicate,true);
 assert.equal(DB.sqlite.prepare('SELECT COUNT(*) AS n FROM attempts').get().n,1);
 await api('/progress',{...event,eventId:crypto.randomUUID(),correct:false},parent);
 await api('/progress',{...event,eventId:crypto.randomUUID(),correct:true},parent);
 const review=(await api('/homework?child='+kid,undefined,parent)).body.progress['pu-starter-u7-climb'];assert.equal(review.step,0);assert.ok(review.due<initial.due,'Immediate correction preserves the short retry interval');
 await api('/progress',{childId:kid,assignmentId,activity:'picture-listen',complete:true},parent);
 assert.equal((await api('/homework?child='+kid,undefined,parent)).body.completed.length,1);
 const reports=(await api('/teacher',undefined,teacher)).body.reports;assert.equal(reports[0].attempts,3);assert.equal(reports[0].correct,2);
 // Revised assignments preserve word schedules but reset the explicit family checklist.
 await api('/assignments',{...payload,id:assignmentId,title:'Updated homework'},teacher);
 homework=(await api('/homework?child='+kid,undefined,parent)).body;assert.equal(homework.assignments[0].title,'Updated homework');assert.equal(homework.completed.length,0);assert.deepEqual(homework.progress['pu-starter-u7-climb'],review);
 await api('/approve',{childId:kid,approved:false},teacher);assert.equal((await api('/progress',event,parent)).status,400);
 assert.equal((await api('/homework?child='+kid,undefined,parent)).body.assignments.length,0);
 const replacement=(await api('/invite',{groupId:a.id},teacher)).body.invite;
 assert.equal((await api('/children',{name:'Ben',invite:a.invite},parent)).status,400);
 assert.equal((await api('/children',{name:'Ben',invite:replacement},parent)).status,200);
 await api('/logout',{},parent);assert.equal((await api('/family',undefined,parent)).status,401);
 const login=await api('/login',{username:'panda_family',password:'parent-password'});assert.equal(login.status,200);assert.equal((await api('/family',undefined,login.body.token)).body.children.length,2);
 DB.sqlite.close();
});
test('origin checks and authentication are enforced',async()=>{
 const {api,DB}=setup();assert.equal((await api('/teacher')).status,401);
 const r=await handle(new Request('https://classroom.test/teacher',{headers:{Origin:'https://untrusted.test'}}),{DB,ALLOWED_ORIGINS:origin,TEACHER_PASSWORD:'test'});assert.equal(r.status,403);DB.sqlite.close();
});
