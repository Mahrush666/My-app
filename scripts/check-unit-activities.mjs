import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const compiled=ts.transpileModule(fs.readFileSync('lib/unit-activities.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;
const context={exports:{},URL,URLSearchParams,location:{href:'https://example.com/My-app/?v=1#view=teacher'}};
vm.runInNewContext(compiled,context);
const {validateSettings,settingsLink,spokenMatch,youngActivities}=context.exports;
const valid=validateSettings({'animals':{age:'3–5',activities:youngActivities},'unknown':{activities:['reading']},'bad':{activities:['admin']},'empty':{activities:[]}},['animals','bad','empty']);
assert.equal(Object.keys(valid).join(','),'animals');
const url=new URL(settingsLink(valid,'animals'));
const hash=new URLSearchParams(url.hash.slice(1));
assert.equal(hash.get('unit'),'animals');
assert.deepEqual(JSON.parse(hash.get('settings')),JSON.parse(JSON.stringify(valid)));
assert.equal(hash.has('view'),false);
assert.equal(url.origin,'https://example.com');
assert.equal(spokenMatch('Cat!','cat'),true);
assert.equal(spokenMatch('A cat.','cat'),true);
assert.equal(spokenMatch("It's a cat!",'cat'),true);
assert.equal(spokenMatch('dog','cat'),false);
assert.equal(spokenMatch('not a cat','cat'),false);
assert.equal(spokenMatch('cat and dog','cat'),false);
assert.equal(spokenMatch('','cat'),false);
assert.equal(spokenMatch('wait here','wait here'),true);
assert.equal(spokenMatch('wait','wait here'),false);
console.log('Unit settings sharing, malformed settings, and speech target checks passed.');
