 await db.prepare('INSERT INTO daily_runs VALUES(?,?,?,?,?,?,?)').bind('run','a','g','2026-11-03','[]',week.start,0).run();
 await db.prepare('INSERT INTO daily_answers VALUES(?,?,?,?,?,?)').bind('answer','run','task',0,week.start+86400000,'wrong').run();
